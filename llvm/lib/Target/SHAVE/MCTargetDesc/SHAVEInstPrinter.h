#ifndef SHAVEINSTPRINTER_H
#define SHAVEINSTPRINTER_H (1)


#include "llvm/MC/MCInstPrinter.h"
#include "llvm/MC/MCInstrInfo.h"


namespace llvm {
  class SHAVEInstPrinter : public MCInstPrinter {
  public:
    SHAVEInstPrinter(const MCAsmInfo &MAI,
                     const MCInstrInfo &MII,
                     const MCRegisterInfo &MRI)
    : MCInstPrinter(MAI, MII, MRI)
    {}

    // Override these methods
    void printInst(const MCInst *MI, uint64_t Address, StringRef Annot, const MCSubtargetInfo &STI, raw_ostream &O) override;
    std::pair<const char *, uint64_t> getMnemonic(const MCInst *MI) override;
    void printRegName(raw_ostream &OS, MCRegister Reg) const override;

    // Declarations for the assembler printer whose implementation is generated by TableGen
    void printInstruction(const MCInst *MI, uint64_t Address, raw_ostream &O);
    static const char *getRegisterName(MCRegister Reg);

    // Support routines required for the assembly printer
    void printByteEnableOperand(const MCInst *MI, int opNum,
                                raw_ostream &O) const;
    void printCMBSize(const MCInst *MI, int opNum,
                      raw_ostream &O) const;
    void printFUnitOperand(const MCInst *MI, int opNum, raw_ostream &O) const;
    void printConstFloatOperand(const MCInst *MI,
                                int opNum, raw_ostream &O) const;
    void printMemOffsetOperand(const MCInst *MI,
                               int opNum, raw_ostream &O) const;
    void printVSZMOperand(const MCInst *MI, int opNum, raw_ostream &O) const;
    void printSWZM4Operand(const MCInst *MI, int opNum, raw_ostream &O) const { printSWZM8Operand(MI, opNum, O); }
    void printSWZM8Operand(const MCInst *MI, int opNum, raw_ostream &O) const;
    void printOperand(const MCInst *MI, int opNum, raw_ostream &O) const;
    void PrintSpecial(const MCInst *MI, raw_ostream &OS,
                      const char *Code) const;
    void printVSZMSelectBitsExtract8(const MCInst *MI, int opNum, raw_ostream &O) const;
    void printVSZMSelectBitsExtract16(const MCInst *MI, int opNum, raw_ostream &O) const;
    void printVSZMSelectBitsInsert8(const MCInst *MI, int opNum, raw_ostream &O) const;
    void printVSZMSelectBitsInsert16(const MCInst *MI, int opNum, raw_ostream &O) const;
  };
} // End of namespace llvm


#endif // SHAVEINSTPRINTER_H
